import { toCsvSections } from '@/lib/export/csv';
import { usd } from './build';
import type { ViolationReport } from './types';

/**
 * Renders a `ViolationReport` to CSV — the same document as the PDF, in the
 * form a compliance reviewer can actually pivot on.
 *
 * Built on the shared `toCsvSections` (src/lib/export/csv.ts) so the RFC 4180
 * quoting, the record delimiter and the Excel BOM are the ones every other
 * export in the product already uses; this module contributes section titles
 * and row shapes, nothing else.
 *
 * Pure and deterministic, like the PDF renderer: no clock, no randomness, no
 * database. Section order mirrors `ViolationReport`'s field order, which is
 * the order of the trader notice in docs/HOW-IT-WORKS.md §2 Flow 3.
 */

/** The section titles, in order. Exported so a test can assert the order. */
export const VIOLATION_CSV_SECTIONS = [
  'Summary',
  'Rule',
  'Arithmetic',
  'Timeline',
  'Trades',
  'Actions',
  'History',
  'Provenance',
] as const;

function dash(value: string | number | undefined | null): string {
  if (value === undefined || value === null || value === '') return '—';
  return String(value);
}

function money(value: number | undefined): string {
  return value === undefined ? '—' : usd(value);
}

export function renderViolationReportCsv(report: ViolationReport): string {
  return toCsvSections([
    {
      title: 'Summary',
      rows: [
        ['Field', 'Value'],
        ['Report id', report.reportId],
        ['Generated at', report.generatedAt],
        ['Generated by', report.generatedBy],
        ['Firm', report.header.firmName],
        ['Account id', report.header.accountId],
        ['Login', report.header.login],
        ['Trader', dash(report.header.traderName)],
        ['Phase', dash(report.header.phase)],
        ['Plan', dash(report.header.planName)],
        ['Asset class', dash(report.header.assetClass)],
        ['Rule', report.rule.label],
        ['Severity', report.whatHappened.severity],
        ['Status', report.whatHappened.status],
        ['Detected at', report.whatHappened.detectedAt],
        ['Session day', dash(report.whatHappened.sessionDay)],
        ['Observed', report.whatHappened.observed],
        ['Exceeded by', money(report.whatHappened.exceededBy)],
        ['Report schema version', String(report.schemaVersion)],
      ],
    },
    {
      title: 'Rule',
      rows: [
        ['Field', 'Value'],
        ['Rule id', report.rule.id],
        ['Rule label', report.rule.label],
        ['Limit as written', report.rule.limitAsWritten],
        ['Source', report.rule.source],
        ['Action', dash(report.rule.action)],
        ['Rule pack name', dash(report.rule.pack?.name)],
        ['Rule pack version', dash(report.rule.pack?.version)],
        ['Rule pack id', dash(report.rule.pack?.id)],
        ['Rule pack content hash', dash(report.rule.pack?.contentHash)],
      ],
    },
    {
      title: 'Arithmetic',
      rows: [
        ['Line', 'Expression', 'Value'],
        ...report.arithmetic.map((a) => [a.label, a.expression ?? '', a.value]),
      ],
    },
    {
      title: 'Timeline',
      rows: [
        ['At', 'Kind', 'Summary', 'Actor'],
        ...report.timeline.map((t) => [t.at, t.kind, t.summary, t.actor ?? '']),
      ],
    },
    {
      title: 'Trades',
      rows: [
        ['Trade id', 'Symbol', 'Side', 'Volume', 'Opened at', 'Closed at', 'Open price', 'Close price', 'P&L', 'Cited'],
        ...report.trades.map((t) => [
          t.id,
          t.symbol,
          t.side,
          String(t.volume),
          t.openedAt,
          t.closedAt ?? '',
          t.openPrice === undefined ? '' : String(t.openPrice),
          t.closePrice === undefined ? '' : String(t.closePrice),
          t.pnl === undefined ? '' : t.pnl.toFixed(2),
          t.flagged ? 'yes' : 'no',
        ]),
      ],
    },
    {
      title: 'Actions',
      rows: [
        ['Field', 'Value'],
        ['Queue status', dash(report.action.queueStatus)],
        ['Decision', dash(report.action.decision)],
        ['Approver', dash(report.action.approver)],
        ['Decided at', dash(report.action.decidedAt)],
        ['Executed at', dash(report.action.executedAt)],
        ['Deduction amount', money(report.action.deduction?.amount)],
        ['Balance before', money(report.action.deduction?.preBalance)],
        ['Balance after', money(report.action.deduction?.postBalance)],
        ['Executed by', dash(report.action.deduction?.executedBy)],
        ['Account balance', usd(report.accountSnapshot.balance)],
        ['Account equity', usd(report.accountSnapshot.equity)],
        ['Starting balance', usd(report.accountSnapshot.startingBalance)],
        ['Starting day balance', money(report.accountSnapshot.startingDayBalance)],
        ['Starting day equity', money(report.accountSnapshot.startingDayEquity)],
        ['Drawdown floor', money(report.accountSnapshot.drawdownFloor)],
        ['Net transfers', money(report.accountSnapshot.netTransfers)],
      ],
    },
    {
      title: 'History',
      rows: [
        ['Record', 'Id', 'When', 'Rule or status', 'Detail'],
        ...report.history.priorViolations.map((p) => [
          'prior_violation',
          p.id,
          p.detectedAt,
          p.ruleLabel,
          p.status,
        ]),
        ...report.history.disputes.map((d) => [
          'dispute',
          d.id,
          d.openedAt,
          d.status,
          d.resolution ?? '',
        ]),
      ],
    },
    {
      title: 'Provenance',
      rows: [
        ['Field', 'Value'],
        ['Audit chain entry', dash(report.provenance.auditHash)],
        ['Evidence pack id', dash(report.provenance.evidencePackId)],
        ['Source row: violation', 'yes'],
        ['Source row: breach decision', report.provenance.sourceRows.breachDecision ? 'yes' : 'no'],
        ['Source row: evidence pack', report.provenance.sourceRows.evidencePack ? 'yes' : 'no'],
        ['Source row: enforcement queue', report.provenance.sourceRows.enforcementQueue ? 'yes' : 'no'],
        ...report.provenance.dataFidelity.map((line) => ['Data fidelity', line]),
        ...(report.provenance.generatedNarrative
          ? [
              ['Generated narrative disclaimer', report.provenance.generatedNarrative.disclaimer],
              ['Generated narrative', report.provenance.generatedNarrative.text],
            ]
          : []),
      ],
    },
  ]);
}

/**
 * A report paired with the id of the violation it describes.
 *
 * `ViolationReport` deliberately does not carry the violation id — it is the
 * decision record, not a pointer to a row, and the persisted
 * `violation_reports` row already holds the association. The account-level
 * export needs the id as a join key, so callers that have it (the account
 * endpoint, which reads `violation_reports` rows) pass these instead of bare
 * reports; bare reports still work and export an empty id.
 */
export interface AccountViolationReportEntry {
  violationId: string;
  report: ViolationReport;
}

function normalizeEntry(
  entry: ViolationReport | AccountViolationReportEntry
): AccountViolationReportEntry {
  return 'report' in entry ? entry : { violationId: '', report: entry };
}

/**
 * One CSV covering every violation on an account: a Summary section with one
 * row per violation, then a single Trades section carrying a violation_id
 * column so the two can be joined.
 */
export function renderAccountViolationsCsv(
  reports: Array<ViolationReport | AccountViolationReportEntry>
): string {
  const entries = reports.map(normalizeEntry);
  const ordered = [...entries].sort((x, y) => {
    const a = x.report;
    const b = y.report;
    return a.whatHappened.detectedAt < b.whatHappened.detectedAt
      ? 1
      : a.whatHappened.detectedAt > b.whatHappened.detectedAt
        ? -1
        : a.reportId < b.reportId
          ? -1
          : 1;
  });

  return toCsvSections([
    {
      title: 'Summary',
      rows: [
        [
          'violation_id',
          'Report id',
          'Account id',
          'Login',
          'Detected at',
          'Rule',
          'Rule source',
          'Severity',
          'Status',
          'Observed',
          'Limit as written',
          'Exceeded by',
          'Deduction',
          'Cited trades',
        ],
        ...ordered.map(({ violationId, report: r }) => [
          violationId,
          r.reportId,
          r.header.accountId,
          r.header.login,
          r.whatHappened.detectedAt,
          r.rule.label,
          r.rule.source,
          r.whatHappened.severity,
          r.whatHappened.status,
          r.whatHappened.observed,
          r.rule.limitAsWritten,
          r.whatHappened.exceededBy === undefined ? '' : r.whatHappened.exceededBy.toFixed(2),
          r.action.deduction ? r.action.deduction.amount.toFixed(2) : '',
          String(r.trades.filter((t) => t.flagged).length),
        ]),
      ],
    },
    {
      title: 'Trades',
      rows: [
        [
          'violation_id',
          'Report id',
          'Trade id',
          'Symbol',
          'Side',
          'Volume',
          'Opened at',
          'Closed at',
          'Open price',
          'Close price',
          'P&L',
          'Cited',
        ],
        ...ordered.flatMap(({ violationId, report: r }) =>
          r.trades.map((t) => [
            violationId,
            r.reportId,
            t.id,
            t.symbol,
            t.side,
            String(t.volume),
            t.openedAt,
            t.closedAt ?? '',
            t.openPrice === undefined ? '' : String(t.openPrice),
            t.closePrice === undefined ? '' : String(t.closePrice),
            t.pnl === undefined ? '' : t.pnl.toFixed(2),
            t.flagged ? 'yes' : 'no',
          ])
        ),
      ],
    },
  ]);
}
